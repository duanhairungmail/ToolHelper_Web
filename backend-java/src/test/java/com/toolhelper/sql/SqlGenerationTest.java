package com.toolhelper.sql;

import com.toolhelper.support.ApiException;
import java.util.List;
import org.junit.jupiter.api.Test;
import static com.toolhelper.sql.SqlModels.*;
import static org.junit.jupiter.api.Assertions.*;

class SqlGenerationTest {
    private final SqlGenerator generator = new SqlGenerator();
    private Value string(String value) { return new Value("STRING", value); }
    private GenerateRequest request(String type, Select select, Insert insert, Update update, Delete delete, Create create) {
        return new GenerateRequest("MYSQL", "BACKSLASH", type, null, "users", select, insert, update, delete, create);
    }
    @Test void generatesTypedSelectAndQuotesIdentifierByDialect() {
        var select = new Select(List.of(), true, "AND", List.of(new Condition("id", "=", new Value("NUMBER", "900719925474099312345"), null)), List.of(), null);
        assertEquals("SELECT *\nFROM `users`\nWHERE (`id` = 900719925474099312345);", generator.generate(request("SELECT", select, null, null, null, null)).sql());
        var pg = new GenerateRequest("POSTGRESQL", "STANDARD", "INSERT", null, "users", null,
                new Insert(List.of(new Assignment("code", string("O'Reilly\\n")))), null, null, null);
        assertEquals("INSERT INTO \"users\" (\"code\")\nVALUES (E'O''Reilly\\\\n');", generator.generate(pg).sql());
    }
    @Test void rejectsMissingWhereAndSeparatesEmptyFromNull() {
        assertEquals("INSERT INTO `users` (`name`)\nVALUES ('');", generator.generate(request("INSERT", null,
                new Insert(List.of(new Assignment("name", string("")))), null, null, null)).sql());
        var delete = new Delete("AND", List.of());
        ApiException failure = assertThrows(ApiException.class, () -> generator.generate(request("DELETE", null, null, null, delete, null)));
        assertEquals("SQL_WHERE_REQUIRED", failure.code());
        assertThrows(ApiException.class, () -> generator.generate(request("INSERT", null,
                new Insert(List.of(new Assignment("code", new Value("NUMBER", "00123")))), null, null, null)));
    }
    @Test void createsDialectSpecificTableCommentsAndIdentity() {
        var column = new Column("id", "INTEGER", null, null, null, false, true, false, true, null);
        var pg = new GenerateRequest("POSTGRESQL", "STANDARD", "CREATE_TABLE", null, "items", null, null, null, null,
                new Create(List.of(column), "设备表"));
        var result = generator.generate(pg);
        assertTrue(result.sql().contains("GENERATED BY DEFAULT AS IDENTITY"));
        assertTrue(result.sql().endsWith("COMMENT ON TABLE \"items\" IS E'设备表';"));
        assertEquals(2, result.statementCount());
    }
    @Test void likeContainsEscapesWildcardsWhilePatternKeepsThem() {
        for (String mode : List.of("CONTAINS", "PATTERN")) {
            var select = new Select(List.of(), true, "AND", List.of(new Condition("name", "LIKE", string("50%_!"), mode)), List.of(), null);
            String sql = generator.generate(request("SELECT", select, null, null, null, null)).sql();
            assertTrue(sql.contains(mode.equals("CONTAINS") ? "LIKE '%50!%!_!!%' ESCAPE '!'" : "LIKE '50%_!'"));
            assertDoesNotThrow(() -> new SqlFormatter().format(new FormatRequest("MYSQL", "BACKSLASH", sql, "UPPER", 4)));
        }
        var invalid = new Delete("AND", List.of(new Condition("", "=", string("x"), null)));
        assertThrows(ApiException.class, () -> generator.generate(request("DELETE", null, null, null, invalid, null)));
        var nullComparison = new Delete("OR", List.of(new Condition("id", "=", new Value("NULL", null), null)));
        assertThrows(ApiException.class, () -> generator.generate(request("DELETE", null, null, null, nullComparison, null)));
    }
    @Test void defaultValuesRespectColumnTypeRangePrecisionAndNullability() {
        for (Column column : List.of(
                new Column("n", "SMALLINT", null, null, null, true, false, false, false, new Value("NUMBER", "32768")),
                new Column("n", "DECIMAL", null, 4, 2, true, false, false, false, new Value("NUMBER", "100.00")),
                new Column("n", "DECIMAL", null, 4, 2, true, false, false, false, new Value("NUMBER", "1.234")),
                new Column("n", "VARCHAR", 2, null, null, true, false, false, false, string("abc")),
                new Column("n", "INTEGER", null, null, null, false, false, false, false, new Value("NULL", null)),
                new Column("n", "BOOLEAN", null, null, null, true, false, false, false, string("true")))) {
            assertThrows(ApiException.class, () -> generator.generate(request("CREATE_TABLE", null, null, null, null, new Create(List.of(column), null))));
        }
        var valid = new Column("n", "DECIMAL", null, 4, 2, false, false, false, false, new Value("NUMBER", "-99.99"));
        assertTrue(generator.generate(request("CREATE_TABLE", null, null, null, null, new Create(List.of(valid), null))).sql().contains("DEFAULT -99.99"));
    }
    @Test void generatedStatementsCanBeSentToFormatterForBothDialects() {
        var select = new Select(List.of(), true, "AND", List.of(), List.of(), null);
        var values = List.of(new Assignment("name", string("a  b\\c")));
        var conditions = List.of(new Condition("id", "=", new Value("NUMBER", "1"), null));
        var column = new Column("id", "INTEGER", null, null, null, false, true, false, true, null);
        for (String dialect : List.of("MYSQL", "POSTGRESQL")) {
            String escape = dialect.equals("MYSQL") ? "BACKSLASH" : "STANDARD";
            for (var input : List.of(
                    new GenerateRequest(dialect, escape, "SELECT", null, "users", select, null, null, null, null),
                    new GenerateRequest(dialect, escape, "INSERT", null, "users", null, new Insert(values), null, null, null),
                    new GenerateRequest(dialect, escape, "UPDATE", null, "users", null, null, new Update(values, "AND", conditions), null, null),
                    new GenerateRequest(dialect, escape, "DELETE", null, "users", null, null, null, new Delete("AND", conditions), null),
                    new GenerateRequest(dialect, escape, "CREATE_TABLE", null, "users", null, null, null, null, new Create(List.of(column), "表用途")))) {
                String sql = generator.generate(input).sql();
                assertDoesNotThrow(() -> new SqlFormatter().format(new FormatRequest(dialect, escape, sql, "UPPER", 4)), dialect + ":" + input.statementType());
            }
        }
    }
}
